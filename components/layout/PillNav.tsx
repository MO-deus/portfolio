"use client";
import { useState, useEffect } from "react";
import styles from "./PillNav.module.css";

const navItems = [
  { id: "home",       label: "Home",       icon: <HomeIcon /> },
  { id: "work",       label: "Case Studies",icon: <WorkIcon /> },
  { id: "projects",   label: "Projects",   icon: <FolderIcon /> },
  { id: "experience", label: "Experience", icon: <BriefcaseIcon /> },
  { id: "skills",     label: "Skills",     icon: <SkillsIcon /> },
  { id: "contact",    label: "Contact",    icon: <MailIcon /> },
];

export default function PillNav() {
  const [active, setActive] = useState("home");

  useEffect(() => {
    const sections = navItems.map((n) => document.getElementById(n.id)).filter(Boolean) as HTMLElement[];
    const obs = new IntersectionObserver(
      (entries) => {
        entries.forEach((e) => {
          if (e.isIntersecting) setActive(e.target.id);
        });
      },
      { rootMargin: "-40% 0px -55% 0px" }
    );
    sections.forEach((s) => obs.observe(s));
    return () => obs.disconnect();
  }, []);

  return (
    <nav className={styles.nav} aria-label="Page navigation">
      <div className={styles.pill}>
        {navItems.map((item) => (
          <a
            key={item.id}
            href={`#${item.id}`}
            className={`${styles.item} ${active === item.id ? styles.itemActive : ""}`}
            aria-label={item.label}
            title={item.label}
          >
            {item.icon}
          </a>
        ))}
      </div>
    </nav>
  );
}

